"""Generate ed25519_table.h, the precomputed multiples of the base point B
of Ed25519, for the fixed-base scalar multiplication in ed25519.c:

    table[j][m-1] = m * 256^j * B        for j = 0..POSITIONS-1, m = 1..8

Each point (x, y) is stored as (y + x, y - x, 2*d*x*y) modulo p, in the
mixed radix 2^26/2^25 of mod25519.c (10 limbs, little-endian).

Usage: python make_ed25519_table.py > ed25519_table.h
"""

p = 2**255 - 19
d = (-121665 * pow(121666, -1, p)) % p
Bx = 0x216936D3CD6E53FEC0A4E231FDD6DC5C692CC7609525A7B2C9562D608F25D51A
By = 0x6666666666666666666666666666666666666666666666666666666666666658

# A blinded scalar of 32 bytes is smaller than 2^289: 73 digits in radix 16,
# plus one for the carry of the signed recoding, so 37 pairs of digits
POSITIONS = 37

# Bit position and width of each limb
LIMBS = [
    (0, 26),
    (26, 25),
    (51, 26),
    (77, 25),
    (102, 26),
    (128, 25),
    (153, 26),
    (179, 25),
    (204, 26),
    (230, 25),
]


def add(P, Q):
    (x1, y1), (x2, y2) = P, Q
    t = d * x1 * x2 * y1 * y2 % p
    x3 = (x1 * y2 + x2 * y1) * pow(1 + t, -1, p) % p
    y3 = (y1 * y2 + x1 * x2) * pow(1 - t, -1, p) % p
    return x3, y3


def limbs(v):
    return [(v >> pos) & ((1 << width) - 1) for pos, width in LIMBS]


def fe(v):
    return "{ " + ", ".join("0x%07x" % limb for limb in limbs(v)) + " }"


def main():
    assert (-Bx * Bx + By * By - 1 - d * Bx * Bx * By * By) % p == 0

    print("/* Generated by make_ed25519_table.py: do not edit */")
    print()
    print("#define ED25519_TABLE_POSITIONS %d" % POSITIONS)
    print()
    print("/* The base point B (little-endian) */")
    for name, v in (("x", Bx), ("y", By)):
        data = ", ".join("0x%02x" % b for b in v.to_bytes(32, "little"))
        print("static const uint8_t ed25519_base_%s[32] = { %s };" % (name, data))
    print()
    print("/* table[j][m-1] = m * 256^j * B, as (y + x, y - x, 2dxy) */")
    print("static const uint32_t ed25519_table[ED25519_TABLE_POSITIONS][8][3][10] = {")
    base = (Bx, By)
    for j in range(POSITIONS):
        print("  { /* 256^%d * B */" % j)
        point = base
        for m in range(1, 9):
            x, y = point
            print("    { %s," % fe((y + x) % p))
            print("      %s," % fe((y - x) % p))
            print("      %s }%s" % (fe(2 * d * x * y % p), "," if m < 8 else ""))
            point = add(point, base)
        print("  }%s" % ("," if j < POSITIONS - 1 else ""))
        # The next base: 256 * base
        for _ in range(8):
            base = add(base, base)
    print("};")


if __name__ == "__main__":
    main()
