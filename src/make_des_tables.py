"""Generate des_tables.h, the S-box tables for the constant-time DES in DES.c.

Each output bit of each S-box is stored as a 64-bit truth table, indexed
directly by the 6-bit S-box input (b1 is the most significant bit), so that
the lookup becomes a shift by a secret amount instead of a memory access
at a secret address.

Next to each truth table we store the position (0 = least significant bit)
that the bit takes in the 32-bit output of the round function, after the
permutation P.

Usage: python make_des_tables.py > des_tables.h
"""

