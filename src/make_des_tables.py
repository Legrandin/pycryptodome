def sbox(j, x):
    row = ((x >> 4) & 2) | (x & 1)
    col = (x >> 1) & 15
    return S[j][row * 16 + col]


def main():
    print("/* Generated by make_des_tables.py - do not edit */")
    print()
    print("/* des_tt[j][k] has bit x set if bit k (0 is the MSB) of S-box j+1 is set for input x */")
    print("static const uint64_t des_tt[8][4] = {")
    for j in range(8):
        words = []
        for k in range(4):
            tt = sum(((sbox(j, x) >> (3 - k)) & 1) << x for x in range(64))
            words.append("0x%016XULL" % tt)
        print("    { %s }," % ", ".join(words))
    print("};")
    print()
    print("/* des_pos[j][k] is the position of bit k of S-box j+1 after the permutation P */")
    print("static const unsigned des_pos[8][4] = {")
    for j in range(8):
        pos = [32 - (P.index(4 * j + k + 1) + 1) for k in range(4)]
        print("    { %s }," % ", ".join("%2d" % p for p in pos))
    print("};")


if __name__ == "__main__":
    main()
