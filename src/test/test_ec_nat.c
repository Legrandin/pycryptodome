static uint64_t rnd_state = 0x0123456789ABCDEFULL;

static uint64_t rnd(void)
{
    /* xorshift64 */
    rnd_state ^= rnd_state << 13;
    rnd_state ^= rnd_state >> 7;
    rnd_state ^= rnd_state << 17;
    return rnd_state;
}

/** Hex string to big-endian bytes, right-aligned in len bytes (returns len) **/
static size_t from_hex(uint8_t *out, size_t len, const char *hex)
{
    size_t digits = strlen(hex), i;

    assert((digits + 1) / 2 <= len);
    memset(out, 0, len);
    for (i=0; i<digits; i++) {
        char ch = hex[digits - 1 - i];
        unsigned v = (ch >= '0' && ch <= '9') ? (unsigned)(ch - '0') : (unsigned)(ch - 'a' + 10);

        out[len - 1 - i/2] |= (uint8_t)(v << (4*(i % 2)));
    }
    return len;
}

static EcCurve *load_curve(const TestCurve *tc)
{
    uint8_t p[MAX_LEN], b[MAX_LEN], n[MAX_LEN], gx[MAX_LEN], gy[MAX_LEN];
    EcCurve *c;
    size_t len = tc->len;

    from_hex(p, len, tc->p);
    from_hex(b, len, tc->b);
    from_hex(n, len, tc->n);
    from_hex(gx, len, tc->gx);
    from_hex(gy, len, tc->gy);
    assert(ec_nat_new_curve(&c, p, b, n, gx, gy, len) == 0);
    return c;
}

static EcPointN *load_point(const EcCurve *c, const char *x, const char *y)
{
    uint8_t xb[MAX_LEN], yb[MAX_LEN];
    EcPointN *p;

    from_hex(xb, c->len, x);
    from_hex(yb, c->len, y);
    assert(ec_nat_new_point(&p, xb, yb, c->len, c) == 0);
    return p;
}

static void check_point(const EcPointN *p, const char *x, const char *y)
{
    uint8_t xb[MAX_LEN], yb[MAX_LEN], xe[MAX_LEN], ye[MAX_LEN];
    size_t len = p->curve->len;

    from_hex(xe, len, x);
    from_hex(ye, len, y);
    assert(ec_nat_get_xy(xb, yb, len, p) == 0);
    assert(memcmp(xb, xe, len) == 0);
    assert(memcmp(yb, ye, len) == 0);
}

static void check_equal(const EcPointN *a, const EcPointN *b)
{
    uint8_t xa[MAX_LEN], ya[MAX_LEN], xb[MAX_LEN], yb[MAX_LEN];
    size_t len = a->curve->len;

    assert(ec_nat_get_xy(xa, ya, len, a) == 0);
    assert(ec_nat_get_xy(xb, yb, len, b) == 0);
    assert(memcmp(xa, xb, len) == 0);
    assert(memcmp(ya, yb, len) == 0);
    assert(ec_nat_cmp(a, b) == 0);
}

static void test_new_curve(const TestCurve *tc)
{
    uint8_t p[MAX_LEN], b[MAX_LEN], n[MAX_LEN], gx[MAX_LEN], gy[MAX_LEN];
    EcCurve *c;
    size_t len = tc->len;

    from_hex(p, len, tc->p);
    from_hex(b, len, tc->b);
    from_hex(n, len, tc->n);
    from_hex(gx, len, tc->gx);
    from_hex(gy, len, tc->gy);

    assert(ec_nat_new_curve(NULL, p, b, n, gx, gy, len) == ERR_NULL);
    assert(ec_nat_new_curve(&c, p, NULL, n, gx, gy, len) == ERR_NULL);
    assert(ec_nat_new_curve(&c, p, b, n, gx, gy, 0) == ERR_VALUE);

    /* b not smaller than p */
    assert(ec_nat_new_curve(&c, p, p, n, gx, gy, len) == ERR_VALUE);
    assert(c == NULL);

    /* A generator that is not on the curve */
    gy[len-1] ^= 1;
    assert(ec_nat_new_curve(&c, p, b, n, gx, gy, len) == ERR_EC_POINT);
    assert(c == NULL);
    gy[len-1] ^= 1;

    assert(ec_nat_new_curve(&c, p, b, n, gx, gy, len) == 0);
    assert(c->len == len);
    assert(c->nw == (len + 7) / 8);
    assert(c->k_words*64 >= (size_t)nat_bit_length(c->order) + EC_BLINDING_BITS);
    assert(c->windows*EC_WINDOW > (size_t)nat_bit_length(c->order) + EC_BLINDING_BITS);
    ec_nat_free_curve(c);
    ec_nat_free_curve(NULL);
}

static void test_points(const TestCurve *tc, const EcCurve *c)
{
    uint8_t x[MAX_LEN], y[MAX_LEN], p[MAX_LEN], zero[MAX_LEN];
    size_t len = c->len;
    EcPointN *g, *q, *pai, *t, *u;

    memset(zero, 0, len);
    from_hex(x, len, tc->gx);
    from_hex(y, len, tc->gy);
    from_hex(p, len, tc->p);

    /* Errors */
    assert(ec_nat_new_point(NULL, x, y, len, c) == ERR_NULL);
    assert(ec_nat_new_point(&t, x, y, 0, c) == ERR_NOT_ENOUGH_DATA);
    assert(ec_nat_new_point(&t, x, y, len + 1, c) == ERR_VALUE);
    assert(ec_nat_new_point(&t, p, zero, len, c) == ERR_EC_POINT);
    assert(t == NULL);
    y[len-1] ^= 1;
    assert(ec_nat_new_point(&t, x, y, len, c) == ERR_EC_POINT);
    assert(t == NULL);
    assert(ec_nat_new_point(&t, zero, y, len, c) == ERR_EC_POINT);
    y[len-1] ^= 1;

    g = load_point(c, tc->gx, tc->gy);
    q = load_point(c, tc->qx, tc->qy);
    pai = load_point(c, "0", "0");
    check_point(g, tc->gx, tc->gy);
    check_point(pai, "0", "0");

    /* get_xy */
    assert(ec_nat_get_xy(x, y, len - 1, g) == ERR_NOT_ENOUGH_DATA);
    assert(ec_nat_get_xy(NULL, y, len, g) == ERR_NULL);
    {
        uint8_t xl[MAX_LEN+8], yl[MAX_LEN+8];

        /* A longer output is padded with zeros */
        assert(ec_nat_get_xy(xl, yl, len + 8, g) == 0);
        from_hex(x, len, tc->gx);
        assert(memcmp(xl, zero, 8) == 0);
        assert(memcmp(xl + 8, x, len) == 0);
    }

    /* cmp */
    assert(ec_nat_cmp(g, g) == 0);
    assert(ec_nat_cmp(g, q) == ERR_VALUE);
    assert(ec_nat_cmp(g, pai) == ERR_VALUE);
    assert(ec_nat_cmp(pai, pai) == 0);

    /* clone and copy */
    assert(ec_nat_clone(&t, q) == 0);
    check_equal(t, q);
    assert(ec_nat_copy(t, g) == 0);
    check_equal(t, g);

    /* 2G = G + G, with different Z */
    assert(ec_nat_clone(&u, g) == 0);
    assert(ec_nat_double(t) == 0);
    assert(ec_nat_add(u, g) == 0);
    check_equal(t, u);
    check_point(t, tc->cases[2].rx, tc->cases[2].ry);
    assert(ec_nat_cmp(t, g) == ERR_VALUE);

    /* G + (-G) = 0; -0 = 0; 0 + 0 = 0; 2*0 = 0; 0 + G = G */
    assert(ec_nat_copy(t, g) == 0);
    assert(ec_nat_copy(u, g) == 0);
    assert(ec_nat_neg(u) == 0);
    check_point(u, tc->cases[8].rx, tc->cases[8].ry);   /* (n-1)G */
    assert(ec_nat_add(t, u) == 0);
    check_equal(t, pai);
    assert(ec_nat_neg(t) == 0);
    check_equal(t, pai);
    assert(ec_nat_add(t, pai) == 0);
    check_equal(t, pai);
    assert(ec_nat_double(t) == 0);
    check_equal(t, pai);
    assert(ec_nat_add(t, g) == 0);
    check_equal(t, g);

    /* (2G + G) = 3G = G + 2G */
    assert(ec_nat_copy(t, g) == 0);
    assert(ec_nat_double(t) == 0);
    assert(ec_nat_add(t, g) == 0);
    assert(ec_nat_copy(u, g) == 0);
    {
        EcPointN *v;

        assert(ec_nat_clone(&v, g) == 0);
        assert(ec_nat_double(v) == 0);
        assert(ec_nat_add(u, v) == 0);
        check_equal(t, u);
        ec_nat_free_point(v);
    }

    assert(ec_nat_add(NULL, g) == ERR_NULL);
    assert(ec_nat_double(NULL) == ERR_NULL);
    assert(ec_nat_neg(NULL) == ERR_NULL);

    ec_nat_free_point(g);
    ec_nat_free_point(q);
    ec_nat_free_point(pai);
    ec_nat_free_point(t);
    ec_nat_free_point(u);
    ec_nat_free_point(NULL);
}

