/* Booth recoding: the sum of digit_i * 32^i gives back k (mod 2^64, words 0 and 1) */
static void test_booth(void)
{
    uint64_t k[4], sign, digit;
    unsigned t;
    size_t i;

    assert(ec_get_bits((const uint64_t[]){0xF0, 0}, 2, 4, 4) == 0xF);
    assert(ec_get_bits((const uint64_t[]){0x8000000000000000ULL, 1}, 2, 63, 2) == 3);
    assert(ec_get_bits((const uint64_t[]){1, 1}, 2, 64, 6) == 1);
    assert(ec_get_bits((const uint64_t[]){1, 1}, 2, 126, 6) == 0);

    for (t=0; t<1000; t++) {
        uint64_t lo = 0, hi = 0;

        k[0] = rnd();
        k[1] = rnd();
        k[2] = rnd() >> 1;
        k[3] = 0;
        if (t < 3)
            k[0] = k[1] = k[2] = t == 0 ? 0 : (t == 1 ? ~(uint64_t)0 >> 1 : 0x8421084210842108ULL);

        /* The digits, from the top: acc = acc*32 + digit (128 bits) */
        for (i=(3*64 + EC_WINDOW)/EC_WINDOW; i-- > 0;) {
            uint64_t d;

            ec_booth_digit(k, 4, i, &sign, &digit);
            assert(digit <= 16);
            assert(sign <= 1);
            hi = (hi << 5) | (lo >> 59);
            lo <<= 5;
            d = sign ? (uint64_t)0 - digit : digit;
            /* lo + d (signed), with carry into hi */
            if (sign) {
                hi -= (lo < digit);
                lo -= digit;
            } else {
                lo += d;
                hi += (lo < d);
            }
        }
        assert(lo == k[0]);
        assert(hi == k[1]);
    }
}

static void test_blind_scalar(const EcCurve *c)
{
    uint8_t k[MAX_LEN];
    uint64_t kb[16];
    Nat *knat, *r1, *r2, kbn;
    unsigned t;

    assert(nat_new(&knat, c->nw + 8) == 0);
    assert(nat_new(&r1, c->nw) == 0);
    assert(nat_new(&r2, c->nw) == 0);
    kbn.nw = c->k_words;
    kbn.w = kb;

    for (t=0; t<20; t++) {
        size_t len = t < 10 ? c->len : c->len + 40;
        size_t i;

        for (i=0; i<len; i++)
            k[i] = (uint8_t)rnd();
        assert(ec_blind_scalar(kb, c->k_words, c->order, k, len, rnd()) == 0);
        assert((size_t)nat_bit_length(&kbn) <= (size_t)nat_bit_length(c->order) + EC_BLINDING_BITS);
        /* kb = k (mod n) */
        assert(nat_from_bytes(knat, k, len, 0) == 0);
        assert(nat_divmod(NULL, r1, knat, c->order) == 0);
        assert(nat_divmod(NULL, r2, &kbn, c->order) == 0);
        assert(nat_cmp(r1, r2) == 0);
    }

    /* r = 0: k mod n itself */
    memset(k, 0xFF, c->len);
    assert(ec_blind_scalar(kb, c->k_words, c->order, k, c->len, 0) == 0);
    assert(nat_from_bytes(knat, k, c->len, 0) == 0);
    assert(nat_divmod(NULL, r1, knat, c->order) == 0);
    for (t=0; t<c->k_words; t++)
        assert(kb[t] == nat_word(r1, t));

    nat_free(knat);
    nat_free(r1);
    nat_free(r2);
}

